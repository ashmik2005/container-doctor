"""Generate the LaTeX results tables for the report from results/*.json.

Run:  .venv/bin/python report/make_tables.py
Numbers are never typed into the report by hand; they come from eval.py output.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
v1 = {(r["scenario"], r["mode"]): r for r in json.loads((ROOT / "results/eval_results_v1.json").read_text())}
v2 = {(r["scenario"], r["mode"]): r for r in json.loads((ROOT / "results/eval_results.json").read_text())}
names = sorted({k[0] for k in v2})


def summary_row(d, mode, label):
    s = [r for k, r in d.items() if k[1] == mode]
    n = len(s)
    return (f"{mode.replace('_', r'\_')} & {label} & {sum(r['correct'] for r in s)}/{n} & "
            f"{sum(r['steps'] for r in s) / n:.1f} & {sum(r['tool_calls'] for r in s) / n:.1f} & "
            f"{sum(r['seconds'] for r in s) / n:.0f} & {sum(r['used_runbooks'] for r in s)}/{n} \\\\")


summary = [r"\begin{tabular}{llccccc}", r"\toprule",
           r"Mode & Run & Correct & Avg steps & Avg tool calls & Avg time (s) & Searched runbooks \\",
           r"\midrule",
           summary_row(v1, "no_rag", "v1"), summary_row(v2, "no_rag", "v2"), r"\midrule",
           summary_row(v1, "rag", "v1"), summary_row(v2, "rag", "v2"),
           r"\bottomrule", r"\end{tabular}"]

mark = lambda r: r"\cmark" if r["correct"] else r"\xmark"
per = [r"\begin{tabular}{lcccc}", r"\toprule",
       r"Scenario & \multicolumn{2}{c}{no\_rag} & \multicolumn{2}{c}{rag} \\",
       r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}", r" & v1 & v2 & v1 & v2 \\", r"\midrule"]
for n in names:
    label = n[3:].replace("_", " ")
    per.append(f"{n[:2]} {label} & {mark(v1[(n, 'no_rag')])} & {mark(v2[(n, 'no_rag')])} & "
               f"{mark(v1[(n, 'rag')])} & {mark(v2[(n, 'rag')])} \\\\")
per += [r"\bottomrule", r"\end{tabular}"]

out = ROOT / "report/results_tables.tex"
out.write_text("% Generated by report/make_tables.py from results/*.json. Do not edit.\n"
               "\\newcommand{\\SummaryTable}{%\n" + "\n".join(summary) + "}\n"
               "\\newcommand{\\PerScenarioTable}{%\n" + "\n".join(per) + "}\n")
print(f"wrote {out}")
