"""REST API for Container Doctor, built with FastAPI.

Run:   .venv/bin/uvicorn api:app --port 8000
Docs:  http://127.0.0.1:8000/docs   (interactive, generated by FastAPI from this file)

Endpoints
  GET  /health            are Ollama and Docker reachable?
  GET  /containers        all containers as JSON
  POST /diagnoses         start a diagnosis      -> 202 Accepted + job id
  GET  /diagnoses/{id}    poll its status        -> queued / running / done / failed
  GET  /diagnoses         list jobs, newest first

Why jobs instead of one long request? A diagnosis takes 1-3 minutes on CPU.
Holding an HTTP request open that long hits client and proxy timeouts, so the
API answers immediately with a job id and the client polls for the result.
"""
import json
import subprocess
import threading
import time
import uuid
from concurrent.futures import ThreadPoolExecutor
from typing import Literal

import ollama
from fastapi import FastAPI, HTTPException, Response
from pydantic import BaseModel, Field

from agent import MODEL, run_agent
from tools import TOOL_SCHEMAS, TOOL_SCHEMAS_NO_RAG, _run

app = FastAPI(
    title="Container Doctor API",
    version="1.0.0",
    description="Diagnose broken Docker containers with a local LLM agent.",
)

# One worker: the laptop CPU can only run one model call at a time, so extra
# jobs wait in the executor's queue (status "queued") instead of competing.
executor = ThreadPoolExecutor(max_workers=1)

# Job store: a plain dict in memory. Simple, but lost on restart and only
# valid for a single server process (see README limitations).
jobs: dict[str, dict] = {}
jobs_lock = threading.Lock()  # the worker thread and request threads both touch `jobs`


# --- Request / response schemas (Pydantic validates input automatically) -----

class DiagnoseRequest(BaseModel):
    question: str = Field(min_length=3, max_length=500,
                          examples=["My web app is down. What is wrong?"])
    use_runbooks: bool = Field(default=True, description="Give the agent the search_runbooks tool.")


class DiagnosisResult(BaseModel):
    answer: str
    steps: int
    tools_used: list[str]
    seconds: float


class Job(BaseModel):
    id: str
    status: Literal["queued", "running", "done", "failed"]
    question: str
    use_runbooks: bool
    created_at: float
    finished_at: float | None = None
    result: DiagnosisResult | None = None
    error: str | None = None
    messages: list[dict] | None = None  # full agent transcript, only on request


class Container(BaseModel):
    name: str
    image: str
    state: str
    status: str
    ports: str


# --- Background work ----------------------------------------------------------

def deny_actions(name: str, args: dict) -> bool:
    """There is no human at an API call, so state-changing tools are always refused."""
    return False


def _run_job(job_id: str) -> None:
    """Runs in the worker thread: execute the agent and store the outcome."""
    with jobs_lock:
        job = jobs[job_id]
        job["status"] = "running"
    schemas = TOOL_SCHEMAS if job["use_runbooks"] else TOOL_SCHEMAS_NO_RAG
    try:
        out = run_agent(job["question"], schemas, approve=deny_actions, verbose=False)
        update = {"status": "done",
                  "result": {k: out[k] for k in ("answer", "steps", "tools_used", "seconds")},
                  "messages": out["messages"]}
    except Exception as e:  # e.g. Ollama stopped mid-run; report it, don't crash the worker
        update = {"status": "failed", "error": f"{type(e).__name__}: {e}"}
    with jobs_lock:
        job.update(update, finished_at=time.time())


def _public(job: dict, include_messages: bool) -> Job:
    """Hide the (long) transcript unless the client asks for it."""
    data = dict(job)
    if not include_messages:
        data["messages"] = None
    return Job(**data)


# --- Endpoints ----------------------------------------------------------------

@app.get("/health")
def health(response: Response) -> dict:
    """Check the two things the agent depends on. 503 if either is down."""
    checks = {}
    try:
        names = [m.model for m in ollama.list().models]
        checks["ollama"] = "ok" if any(n.startswith(MODEL) for n in names) else f"model {MODEL} not pulled"
    except Exception as e:
        checks["ollama"] = f"unreachable: {type(e).__name__}"
    try:
        # Fixed command, list arguments, no shell. Not model-driven, so it does
        # not go through the agent's allowlist.
        r = subprocess.run(["docker", "info", "--format", "{{.ServerVersion}}"],
                           capture_output=True, text=True, timeout=10)
        checks["docker"] = "ok" if r.returncode == 0 else "unreachable"
    except (OSError, subprocess.TimeoutExpired) as e:
        checks["docker"] = f"unreachable: {type(e).__name__}"
    healthy = all(v == "ok" for v in checks.values())
    response.status_code = 200 if healthy else 503
    return {"status": "ok" if healthy else "degraded", **checks}


@app.get("/containers", response_model=list[Container])
def list_containers() -> list[Container]:
    """Same data as the agent's list_containers tool, but as structured JSON."""
    raw = _run(["docker", "ps", "-a", "--format", "{{json .}}"])
    if raw.startswith("ERROR"):
        raise HTTPException(status_code=503, detail=raw)
    if raw == "(no output)":
        return []
    try:
        rows = [json.loads(line) for line in raw.splitlines()]
    except json.JSONDecodeError:
        raise HTTPException(status_code=503, detail=f"unexpected docker output: {raw[:200]}")
    return [Container(name=r["Names"], image=r["Image"], state=r["State"],
                      status=r["Status"], ports=r["Ports"]) for r in rows]


@app.post("/diagnoses", status_code=202, response_model=Job)
def create_diagnosis(req: DiagnoseRequest, response: Response) -> Job:
    """Queue a diagnosis and return immediately. Poll the Location header for the result."""
    job_id = uuid.uuid4().hex[:12]
    job = {"id": job_id, "status": "queued", "question": req.question,
           "use_runbooks": req.use_runbooks, "created_at": time.time()}
    with jobs_lock:
        jobs[job_id] = job
    executor.submit(_run_job, job_id)
    response.headers["Location"] = f"/diagnoses/{job_id}"
    return _public(job, include_messages=False)


@app.get("/diagnoses/{job_id}", response_model=Job)
def get_diagnosis(job_id: str, include_messages: bool = False) -> Job:
    """Current state of one job. ?include_messages=true adds the full agent transcript."""
    with jobs_lock:
        job = jobs.get(job_id)
        if job is None:
            raise HTTPException(status_code=404, detail=f"no diagnosis with id {job_id}")
        return _public(job, include_messages)


@app.get("/diagnoses", response_model=list[Job])
def list_diagnoses(limit: int = 20) -> list[Job]:
    """Most recent jobs first, without transcripts."""
    with jobs_lock:
        recent = sorted(jobs.values(), key=lambda j: j["created_at"], reverse=True)[: max(1, limit)]
        return [_public(j, include_messages=False) for j in recent]
