"""Run the agent on every scenario, with and without the runbook tool, and score it.

Run all:        .venv/bin/python eval.py
Run some:       .venv/bin/python eval.py 01_missing_env_var 02_oom_killed

Writes:
  results/eval_results.md    the results table (committed)
  results/eval_results.json  the same data, machine-readable (committed)
  eval_logs/<scenario>__<mode>.json   full message history of every run (git-ignored)

Scoring (deliberately simple): each scenario lists keyword GROUPS. A diagnosis
is CORRECT if, for every group, at least one keyword appears in the final
answer as a whole word (case-insensitive). See README "Evaluation" for the
weaknesses of this method.
"""
import json
import re
import subprocess
import sys
import time
from pathlib import Path

from agent import MODEL, run_agent
from tools import TOOL_SCHEMAS, TOOL_SCHEMAS_NO_RAG

ROOT = Path(__file__).parent
SCENARIOS = ROOT / "scenarios"
LOG_DIR = ROOT / "eval_logs"
RESULTS_DIR = ROOT / "results"
MODES = {"no_rag": TOOL_SCHEMAS_NO_RAG, "rag": TOOL_SCHEMAS}


def deny_all(name, args) -> bool:
    """Eval is unattended: every state-changing action is refused."""
    return False


def keyword_found(text: str, keyword: str) -> bool:
    """Whole-word, case-insensitive match. "80" must not match inside "8080"."""
    pattern = r"(?<!\w)" + re.escape(keyword.lower()) + r"(?!\w)"
    return re.search(pattern, text.lower()) is not None


def score(answer: str, groups: list[list[str]]) -> tuple[bool, int]:
    """Return (correct, number of groups matched)."""
    matched = sum(any(keyword_found(answer, k) for k in group) for group in groups)
    return matched == len(groups), matched


def scenario(action: str, name: str = "") -> None:
    subprocess.run([str(ROOT / "scenario.sh"), action] + ([name] if name else []),
                   capture_output=True, text=True, check=False)


def run_one(name: str, mode: str, expected: dict) -> dict:
    scenario("up", name)  # fresh, identical starting state for every run
    try:
        result = run_agent(expected["question"], MODES[mode], approve=deny_all, verbose=False)
        error = None
    except Exception as e:  # e.g. Ollama not running; record it, keep going
        result = {"answer": "", "steps": 0, "tools_used": [], "seconds": 0, "messages": []}
        error = f"{type(e).__name__}: {e}"

    answer = result["answer"] or ""
    correct, matched = score(answer, expected["keywords"])
    # Nudges are the extra "user" messages the loop injected after the question.
    nudges = sum(1 for m in result["messages"][2:] if m.get("role") == "user")
    row = {
        "scenario": name, "mode": mode, "correct": correct,
        "groups_matched": f"{matched}/{len(expected['keywords'])}",
        "steps": result["steps"], "tool_calls": len(result["tools_used"]),
        "used_runbooks": "search_runbooks" in result["tools_used"],
        "nudges": nudges, "seconds": result["seconds"], "error": error,
    }
    LOG_DIR.mkdir(exist_ok=True)
    (LOG_DIR / f"{name}__{mode}.json").write_text(json.dumps(
        {**row, "question": expected["question"], "expected": expected["root_cause"],
         "answer": answer, "tools_used": result["tools_used"],
         "messages": result["messages"]}, indent=2))
    return row


def write_results(rows: list[dict], started: str, total_seconds: float) -> None:
    RESULTS_DIR.mkdir(exist_ok=True)
    (RESULTS_DIR / "eval_results.json").write_text(json.dumps(rows, indent=2))

    lines = [
        "# Evaluation results", "",
        f"Model `{MODEL}`, run started {started}, total wall time {total_seconds / 60:.1f} min.",
        "Generated by `eval.py`; do not edit by hand.", "",
        "| Scenario | Mode | Correct | Keyword groups | Steps | Tool calls | Used runbooks | Nudges | Seconds |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        mark = "yes" if r["correct"] else ("ERROR" if r["error"] else "no")
        lines.append(f"| {r['scenario']} | {r['mode']} | {mark} | {r['groups_matched']} | "
                     f"{r['steps']} | {r['tool_calls']} | {'yes' if r['used_runbooks'] else 'no'} | "
                     f"{r['nudges']} | {r['seconds']} |")

    lines += ["", "## Summary", "",
              "| Mode | Correct | Avg steps | Avg tool calls | Avg seconds |", "|---|---|---|---|---|"]
    for mode in MODES:
        sub = [r for r in rows if r["mode"] == mode]
        if not sub:
            continue
        n = len(sub)
        lines.append(f"| {mode} | {sum(r['correct'] for r in sub)}/{n} | "
                     f"{sum(r['steps'] for r in sub) / n:.1f} | "
                     f"{sum(r['tool_calls'] for r in sub) / n:.1f} | "
                     f"{sum(r['seconds'] for r in sub) / n:.1f} |")
    (RESULTS_DIR / "eval_results.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    names = sys.argv[1:] or sorted(p.name for p in SCENARIOS.iterdir() if p.is_dir())
    started, t0 = time.strftime("%Y-%m-%d %H:%M"), time.time()
    rows = []
    for name in names:
        expected = json.loads((SCENARIOS / name / "expected.json").read_text())
        for mode in MODES:
            row = run_one(name, mode, expected)
            rows.append(row)
            print(f"{name:26} {mode:7} correct={row['correct']!s:5} groups={row['groups_matched']} "
                  f"steps={row['steps']} runbooks={row['used_runbooks']!s:5} {row['seconds']}s"
                  + (f" ERROR {row['error']}" if row["error"] else ""), flush=True)
            write_results(rows, started, time.time() - t0)  # save progress after every run
    scenario("down")
    print(f"\nWrote {RESULTS_DIR / 'eval_results.md'}")


if __name__ == "__main__":
    main()
